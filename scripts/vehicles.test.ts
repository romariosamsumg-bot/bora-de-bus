import assert from 'node:assert/strict';
import {visibleVehicles} from '../lib/vehicles.ts';
const now=Date.parse('2026-10-12T12:00:00Z');
const vehicle=(direction:string,shape:string,age=30)=>({direction,shape,time:new Date(now-age*1000).toISOString()});
const positions=[vehicle('I','new-unrecognized-shape'),vehicle('V','other-shape'),vehicle('','known-shape'),vehicle('I','',181),vehicle('I','',-70)];
assert.equal(visibleVehicles(positions,now,false,'0',new Set()).length,3,'all directions includes unknown shapes, excludes stale/future positions');
assert.equal(visibleVehicles(positions,now,true,'0',new Set(['known-shape'])).length,2,'known direction takes priority over obsolete shape; unknown direction can match a shape');
assert.equal(visibleVehicles(positions,now,true,'1',new Set(['new-unrecognized-shape'])).length,1,'opposite direction is not shown because a shape matches');
assert.equal(visibleVehicles([{...positions[0],time:'invalid'}],now,false,'0',new Set()).length,0);
console.log('GPS filtering regression checks passed');
