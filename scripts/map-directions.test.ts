import assert from 'node:assert/strict';
import {mapTrips,vehicleDirection} from '../lib/map-directions.ts';
import {visibleVehicles} from '../lib/vehicles.ts';
const data:any={trips:[{direction:'0',shape:'ida'},{direction:'0',shape:'extra'},{direction:'1',shape:'volta'},{direction:'0',shape:'shared'},{direction:'1',shape:'shared'}]};
assert.deepEqual(mapTrips(data,'all').map(t=>t.direction),['0','1']);
assert.deepEqual(mapTrips(data,'0').map(t=>t.shape),['ida']);
assert.deepEqual(mapTrips(data,'1').map(t=>t.shape),['volta']);
assert.equal(vehicleDirection({direction:'I',shape:'volta'},data),'0');
assert.equal(vehicleDirection({direction:'V',shape:'ida'},data),'1');
assert.equal(vehicleDirection({direction:'',shape:'volta'},data),'1');
assert.equal(vehicleDirection({direction:'',shape:'shared'},data),undefined);
assert.equal(vehicleDirection({direction:'',shape:'new'},data),undefined);
const now=Date.now();const v=['I','V',''].map((direction,i)=>({id:i,direction,shape:'',time:new Date(now).toISOString()}));
const all=visibleVehicles(v,now,false,'0',new Set());
assert.equal(all.length,3);
assert.equal(all.filter(v=>vehicleDirection(v,data)==='0').length,1);
assert.equal(all.filter(v=>vehicleDirection(v,data)==='1').length,1);
assert.deepEqual(mapTrips(null,'all'),[]);
console.log('12 direction-filter checks passed');
